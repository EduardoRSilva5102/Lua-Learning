-- for para contar de 1 a 10
for i = 1, 10 do
    print(i)
end

-- for para contar de 1 a 10 indo de 2 em 2 números
for i = 1, 10, 2 do
    print(i)
end

-- while para contar de 1 a 10
local i = 0
while i <= 10 do
    print(i)
    i = i + 1
end

-- while com "step" de 2 em 2 números
local x = 0
while x <= 10 do
    print(x)
    x = x + 2
end